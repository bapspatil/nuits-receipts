#!/usr/bin/env bun
// Renders the install icons from the app glyph (src/icon.ts) into src/app-icons.ts,
// and copies them to docs/pwa/ for review. Rerun after the glyph changes:
//
//   bun run icons
//
// Uses the Chromium that Playwright cached unless CHROME is set.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { chromium } from 'playwright-core';
import { ICON_SOURCES } from '../src/icon.ts';

const ICONS = [
  { key: 'icon192', file: 'icon-192.png', size: 192, source: 'any', transparent: true },
  { key: 'icon512', file: 'icon-512.png', size: 512, source: 'any', transparent: true },
  { key: 'maskable512', file: 'icon-maskable-512.png', size: 512, source: 'maskable', transparent: false },
  { key: 'apple180', file: 'apple-touch-icon.png', size: 180, source: 'apple', transparent: false },
];

function chromePath() {
  if (process.env.CHROME) return process.env.CHROME;
  const cache = join(homedir(), 'Library/Caches/ms-playwright');
  const builds = existsSync(cache)
    ? readdirSync(cache)
        .filter((d) => /^chromium-\d+$/.test(d))
        .sort()
    : [];
  for (const build of builds.reverse()) {
    for (const app of ['chrome-mac-arm64', 'chrome-mac']) {
      for (const bundle of [
        'Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing',
        'Chromium.app/Contents/MacOS/Chromium',
      ]) {
        const path = join(cache, build, app, bundle);
        if (existsSync(path)) return path;
      }
    }
    const linux = join(cache, build, 'chrome-linux/chrome');
    if (existsSync(linux)) return linux;
  }
  throw new Error('No Chromium found. Set CHROME, or run `npx playwright install chromium`.');
}

const browser = await chromium.launch({ executablePath: chromePath() });
const png = {};
for (const icon of ICONS) {
  const page = await browser.newPage({ viewport: { width: icon.size, height: icon.size } });
  await page.setContent(
    `<style>html,body{margin:0;background:transparent}svg{display:block;width:${icon.size}px;height:${icon.size}px}</style>${ICON_SOURCES[icon.source]}`,
  );
  png[icon.key] = await page.screenshot({ omitBackground: icon.transparent, type: 'png' });
  await page.close();
}
await browser.close();

mkdirSync('docs/pwa', { recursive: true });
for (const icon of ICONS) writeFileSync(join('docs/pwa', icon.file), png[icon.key]);

const hash = createHash('sha256').update(JSON.stringify(ICON_SOURCES)).digest('hex');
const lines = ICONS.map((icon) => `  ${icon.key}: '${png[icon.key].toString('base64')}',`);
writeFileSync(
  'src/app-icons.ts',
  `// Generated by scripts/app-icons.mjs from src/icon.ts. Do not edit by hand.
// Change the glyph and run \`bun run icons\`.

// SHA-256 of JSON.stringify(ICON_SOURCES), the SVGs these PNGs were rendered from.
export const ICON_SOURCE_HASH = '${hash}';

// Base64 PNG bytes.
export const ICON_PNG = {
${lines.join('\n')}
};
`,
);
spawnSync('bunx', ['prettier', '--write', 'src/app-icons.ts'], { stdio: 'inherit' });
console.log('icons written');
